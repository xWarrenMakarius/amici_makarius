import 'package:freezed_annotation/freezed_annotation.dart';

import '../../../domain/entities/user_entity.dart';
import '../../../resources/keys.dart';
import '../features_model/features_model.dart';

part 'user_model.freezed.dart';
part 'user_model.g.dart';

@freezed
abstract class UserModel with _$UserModel {
  const factory UserModel({
    @JsonKey(name: Keys.id, defaultValue: 0)required int id,
    @JsonKey(name: Keys.firstName, defaultValue: '') required String firstName,
    @JsonKey(name: Keys.middleName, defaultValue: '') required String middleName,
    @JsonKey(name: Keys.lastName, defaultValue: '') required String lastName,
    @JsonKey(name: Keys.gender, defaultValue: '') required String gender,
    @JsonKey(name: Keys.birthday, defaultValue: '') required String birthday,
    @JsonKey(name: Keys.subscriptionId, defaultValue: 0) required int subscriptionId,
    @JsonKey(name: Keys.userReferralId, defaultValue: 0) required int userReferralId,
    @JsonKey(name: Keys.branchId, defaultValue: '') required String branchId,
    @JsonKey(name: Keys.batchId, defaultValue: 0) required int batchId,
    @JsonKey(name: Keys.roleId, defaultValue: 0) required int roleId,
    @JsonKey(name: Keys.schoolId, defaultValue: 0) required int schoolId,
    @JsonKey(name: Keys.schoolOthers, defaultValue: '') required String schoolOthers,
    @JsonKey(name: Keys.degree, defaultValue: '') required String degree,
    @JsonKey(name: Keys.nationalityId, defaultValue: 0) required int nationalityId,
    @JsonKey(name: Keys.nationalityOthers, defaultValue: '') required String nationalityOthers,
    @JsonKey(name: Keys.cityId, defaultValue: 0) required int cityId,
    @JsonKey(name: Keys.provinceId, defaultValue: 0) required int provinceId,
    @JsonKey(name: Keys.profilePicture, defaultValue: '') required String profilePicture,
    @JsonKey(name: Keys.contactNoPrefix, defaultValue: '') required String contactNoPrefix,
    @JsonKey(name: Keys.contactNo, defaultValue: '') required String contactNo,
    @JsonKey(name: Keys.email, defaultValue: '') required String email,
    @JsonKey(name: Keys.googleId, defaultValue: '') required String googleId,
    @JsonKey(name: Keys.microsoftId, defaultValue: '') required String microsoftId,
    @JsonKey(name: Keys.emailVerifiedAt, defaultValue: '') required String emailVerifiedAt,
    @JsonKey(name: Keys.isActive, defaultValue: 0) required int isActive,
    @JsonKey(name: Keys.isUpgraded, defaultValue: 0) required int isUpgraded,
    @JsonKey(name: Keys.isTrial, defaultValue: 0) required int isTrial,
    @JsonKey(name: Keys.registrationSource, defaultValue: '') required String registrationSource,
    @JsonKey(name: Keys.approvedBy, defaultValue: 0) required int approvedBy,
    @JsonKey(name: Keys.approvedAt, defaultValue: '') required String approvedAt,
    @JsonKey(name: Keys.lastLogin, defaultValue: '') required String lastLogin,
    @JsonKey(name: Keys.takenDiagnostics, defaultValue: 0) required int takenDiagnostics,
    @JsonKey(name: Keys.features) required FeaturesModel features,
    @JsonKey(name: Keys.createdBy, defaultValue: 0) required int createdBy,
    @JsonKey(name: Keys.updatedBy, defaultValue: 0) required int updatedBy,
    @JsonKey(name: Keys.createdAt, defaultValue: '') required String createdAt,
    @JsonKey(name: Keys.updatedAt, defaultValue: '') required String updatedAt,
    @JsonKey(name: Keys.archivedAt, defaultValue: '') required String archivedAt,
    @JsonKey(name: Keys.isAdmin, defaultValue: false) required bool isAdmin,
    @JsonKey(name: Keys.isBranchAdmin, defaultValue: false) required bool isBranchAdmin,
    @JsonKey(name: Keys.isBranchTeacher, defaultValue: false) required bool isBranchTeacher,
    @JsonKey(name: Keys.isTeacher, defaultValue: false) required bool isTeacher,
    @JsonKey(name: Keys.isStudent, defaultValue: false) required bool isStudent,
    @JsonKey(name: Keys.fullName, defaultValue: '') required String fullName,
    @JsonKey(name: Keys.hasDefaultPassword, defaultValue: false) required bool hasDefaultPassword,
    @JsonKey(name: Keys.isBatchAccessAllowed, defaultValue: false) required bool isBatchAccessAllowed,
    @JsonKey(name: Keys.batchTags, defaultValue: []) required List<dynamic> batchTags,
  }) = _UserModel;

  factory UserModel.fromJson(Map<String, dynamic> json) => _$UserModelFromJson(json);
}

extension UserModelX on UserModel {
  UserEntity toEntity() => UserEntity(
    id: id,
    firstName: firstName,
    middleName: middleName,
    lastName: lastName,
    gender: gender,
    birthday: birthday,
    subscriptionId: subscriptionId,
    userReferralId: userReferralId,
    branchId: branchId,
    batchId: batchId,
    roleId: roleId,
    schoolId: schoolId,
    schoolOthers: schoolOthers,
    degree: degree,
    nationalityId: nationalityId,
    nationalityOthers: nationalityOthers,
    cityId: cityId,
    provinceId: provinceId,
    profilePicture: profilePicture,
    contactNoPrefix: contactNoPrefix,
    contactNo: contactNo,
    email: email,
    googleId: googleId,
    microsoftId: microsoftId,
    emailVerifiedAt: emailVerifiedAt,
    isActive: isActive,
    isUpgraded: isUpgraded,
    isTrial: isTrial,
    registrationSource: registrationSource,
    approvedBy: approvedBy,
    approvedAt: approvedAt,
    lastLogin: lastLogin,
    takenDiagnostics: takenDiagnostics,
    features: features.toEntity(),
    createdBy: createdBy,
    updatedBy: updatedBy,
    createdAt: createdAt,
    updatedAt: updatedAt,
    archivedAt: archivedAt,
    isAdmin: isAdmin,
    isBranchAdmin: isBranchAdmin,
    isBranchTeacher: isBranchTeacher,
    isTeacher: isTeacher,
    isStudent: isStudent,
    fullName: fullName,
    hasDefaultPassword: hasDefaultPassword,
    isBatchAccessAllowed: isBatchAccessAllowed,
    batchTags: batchTags,
      );
}